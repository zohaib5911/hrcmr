"""Application settings (plan.md section 4.1).

Rules enforced here:
  * Every secret is a ``SecretStr``, so ``repr``/``str``/``model_dump`` show ``**********``.
  * ``get_secret_value()`` is called only inside the code that talks to the service
    (the DB engine factory, integration clients), never to log or display.
  * Values come from the environment (Railway in staging/production, the git-ignored
    ``.env`` locally). There are no credentials in this file.
  * Staging and production fail closed: startup stops, naming the missing VARIABLES
    (never their values), if anything required is absent.
"""

from __future__ import annotations

from enum import StrEnum
from functools import lru_cache
from pathlib import Path
from typing import Annotated
from urllib.parse import urlsplit
from zoneinfo import ZoneInfo, ZoneInfoNotFoundError

from pydantic import AfterValidator, Field, SecretStr, field_validator, model_validator
from pydantic_settings import BaseSettings, NoDecode, SettingsConfigDict

# api/app/core/config.py -> repository root. In the container this resolves to a path that has
# no .env, which is fine: deployed environments use real environment variables only.
_REPO_ROOT = Path(__file__).resolve().parents[3]


class AppEnv(StrEnum):
    LOCAL = "local"
    TEST = "test"
    STAGING = "staging"
    PRODUCTION = "production"

    @property
    def is_deployed(self) -> bool:
        return self in (AppEnv.STAGING, AppEnv.PRODUCTION)


def _normalise_origin(value: str) -> str:
    """Accept ``https://example.com`` (optionally with a trailing slash); reject anything else."""
    parts = urlsplit(value.strip())
    if parts.scheme not in ("http", "https") or not parts.hostname:
        raise ValueError("must be an http(s) origin such as https://example.com")
    if parts.path not in ("", "/") or parts.query or parts.fragment or parts.username:
        raise ValueError("must be an origin only: no path, query, fragment or credentials")
    port = f":{parts.port}" if parts.port else ""
    return f"{parts.scheme}://{parts.hostname}{port}"


Origin = Annotated[str, AfterValidator(_normalise_origin)]

# Variables that must be present when APP_ENV is staging or production. They are optional locally
# so a developer can start the API without owning every third-party account.
_REQUIRED_WHEN_DEPLOYED: tuple[str, ...] = (
    "database_url_owner",
    "r2_account_id",
    "r2_endpoint",
    "r2_access_key_id",
    "r2_secret_access_key",
    "r2_bucket_files",
    "resend_api_key",
    "email_from",
    "email_reply_to",
    "support_email",
    "anthropic_api_key",
    "stripe_secret_key",
    "stripe_webhook_secret",
    "stripe_price_annual",
    "stripe_price_ten_year",
    "turnstile_secret_key",
)


class Settings(BaseSettings):
    model_config = SettingsConfigDict(
        env_file=_REPO_ROOT / ".env",
        env_file_encoding="utf-8",
        extra="ignore",
        case_sensitive=False,
        # `NAME=` with nothing after it (as copied from .env.example) means "not set".
        env_ignore_empty=True,
        frozen=True,
    )

    # --- Environment and origins ---------------------------------------------------------------
    app_env: AppEnv
    domain: str
    web_origin: Origin
    admin_origin: Origin
    api_origin: Origin
    tz: str = "Europe/London"
    # Comma-separated networks whose forwarded headers are believed (see core/client_ip.py). Empty
    # means Railway's private network when deployed and nobody on a developer machine.
    trusted_proxy_cidrs: str | None = None

    # --- Database and cache --------------------------------------------------------------------
    database_url: SecretStr
    # Owner credentials are for migrations only; the running API never needs them.
    database_url_owner: SecretStr | None = None
    database_app_user_password: SecretStr | None = None
    redis_url: SecretStr

    # --- Sessions and encryption (generated by the owner, deployment-requirements section 3) ---
    session_secret: SecretStr
    session_cookie_name: str = "brand_session"
    # The platform admin's own session cookie (T17.1). A tenant session never works on the admin
    # routes, and a platform session never works on the tenant routes.
    platform_session_cookie_name: str = "brand_platform_session"
    # The product name in e-mails and in an authenticator app's list (as in brand.config.ts).
    brand_name: str = "Brand"
    field_encryption_keys: SecretStr
    field_encryption_active_kid: str = "k1"
    blind_index_key: SecretStr

    # --- Object storage (Cloudflare R2; RustFS locally) -----------------------------------------
    r2_account_id: str | None = None
    r2_endpoint: str | None = None
    r2_access_key_id: SecretStr | None = None
    r2_secret_access_key: SecretStr | None = None
    r2_bucket_files: str | None = None
    r2_backup_access_key_id: SecretStr | None = None
    r2_backup_secret_access_key: SecretStr | None = None
    r2_bucket_backups: str | None = None
    backup_age_public_key: str | None = None

    # --- E-mail ----------------------------------------------------------------------------------
    resend_api_key: SecretStr | None = None
    email_from: str | None = None
    email_reply_to: str | None = None
    support_email: str | None = None
    # Local development only: with no Resend key but an SMTP host (Mailpit), mail goes there.
    smtp_host: str | None = None
    smtp_port: Annotated[int, Field(ge=1, le=65535)] = 1025

    # --- AI --------------------------------------------------------------------------------------
    anthropic_api_key: SecretStr | None = None
    anthropic_model_main: str = "claude-sonnet-5-5"
    anthropic_model_fast: str = "claude-haiku-5-5"
    ai_features_enabled: bool = True

    # --- Payments --------------------------------------------------------------------------------
    stripe_secret_key: SecretStr | None = None
    stripe_webhook_secret: SecretStr | None = None
    stripe_price_annual: str | None = None
    stripe_price_ten_year: str | None = None

    # --- Other third parties ---------------------------------------------------------------------
    turnstile_secret_key: SecretStr | None = None
    companies_house_api_key: SecretStr | None = None
    # A Sentry DSN is "public-ish" but belongs to the api project and is kept out of the repo.
    sentry_dsn_api: SecretStr | None = None

    # --- Infrastructure ---------------------------------------------------------------------------
    clamav_host: str = "localhost"
    clamav_port: Annotated[int, Field(ge=1, le=65535)] = 3310
    # Comma-separated IPs/CIDRs; empty means no restriction.
    admin_ip_allowlist: Annotated[list[str], NoDecode] = Field(default_factory=list)
    hibp_enabled: bool = True

    @field_validator("admin_ip_allowlist", mode="before")
    @classmethod
    def _split_allowlist(cls, value: object) -> object:
        if isinstance(value, str):
            return [item.strip() for item in value.split(",") if item.strip()]
        return value

    @field_validator("trusted_proxy_cidrs")
    @classmethod
    def _valid_cidrs(cls, value: str | None) -> str | None:
        import ipaddress

        for part in (value or "").split(","):
            if part.strip():
                try:
                    ipaddress.ip_network(part.strip(), strict=False)
                except ValueError as exc:
                    raise ValueError(
                        "must be comma-separated IP networks, e.g. 100.64.0.0/10"
                    ) from exc
        return value

    @field_validator("tz")
    @classmethod
    def _valid_timezone(cls, value: str) -> str:
        try:
            ZoneInfo(value)
        except (ZoneInfoNotFoundError, ValueError) as exc:
            raise ValueError("must be an IANA timezone such as Europe/London") from exc
        return value

    @model_validator(mode="after")
    def _fail_closed_when_deployed(self) -> Settings:
        if self.platform_session_cookie_name == self.session_cookie_name:
            raise ValueError("PLATFORM_SESSION_COOKIE_NAME must differ from SESSION_COOKIE_NAME")
        if self.app_env.is_deployed:
            missing = [name.upper() for name in _REQUIRED_WHEN_DEPLOYED if not getattr(self, name)]
            if missing:
                # Names only: this message can appear in logs.
                raise ValueError(
                    f"APP_ENV={self.app_env.value} requires these variables: {', '.join(missing)}"
                )
            # Keys that cannot encrypt must stop the boot, not the first employee record.
            from app.core.crypto import KeyRing

            KeyRing.from_settings(self)
        return self

    @property
    def docs_enabled(self) -> bool:
        """Interactive API docs are local only. In deployed environments OpenAPI is served to
        authenticated super-admins only (plan.md rule 0.1.11), which arrives with the admin API."""
        return self.app_env in (AppEnv.LOCAL, AppEnv.TEST)


@lru_cache
def get_settings() -> Settings:
    """Process-wide settings, read once. Tests build their own ``Settings`` and pass it in."""
    return Settings()
